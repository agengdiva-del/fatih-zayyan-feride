export function getQuestionsByGradeAndSubject(
  bank: QuizBankDoc[],
  gradeNumber: GradeNumber,
  subjectId?: SubjectId
): LearningQuestion[] {
  const filtered = bank.filter(
    (q) => q.gradeNumber === gradeNumber && (!subjectId || q.subjectId === subjectId)
  );
  // If a subject has fewer than 3 questions for that grade, top up from same grade across subjects so quiz always feels rich
  const pool =
    filtered.length >= 3
      ? filtered
      : [...filtered, ...bank.filter((q) => q.gradeNumber === gradeNumber && q.subjectId !== subjectId)].slice(0, 5);

  return pool.map((doc) => ({
    id: doc.id,
    prompt: doc.prompt,
    options: doc.options,
    correctIndex: doc.correctIndex,
    explanation: doc.explanation,
    gradeNumber: doc.gradeNumber,
    subjectId: doc.subjectId,
    topicTitle: doc.topicTitle,
  }));
}
